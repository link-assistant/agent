// Deliberately narrow translator: refuse unsupported IR or source edits.
// The inventory pins this translator, source and typed intermediate by SHA-256.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const base = new URL('./', import.meta.url);
const read = name => readFileSync(new URL(name, base), 'utf8');
const inventory = JSON.parse(read('parity.json'));
for (const name of ['native.mjs', 'ir.json', 'generate.mjs']) {
  const actual = createHash('sha256').update(read(name)).digest('hex');
  if (inventory.hashes[name] !== actual) throw Error(`Unpinned translation input: ${name}`);
}
const ir = JSON.parse(read('ir.json'));
const supported = { schema: 1, api: 'add', operation: 'checked-add', arguments: ['i32', 'i32'],
  result: 'i32', errors: ['invalid i32', 'overflow'] };
if (JSON.stringify(ir) !== JSON.stringify(supported)) throw Error('Unsupported typed IR');
const fixtures = JSON.parse(read('fixtures.json'));
const tests = fixtures.map((f, i) => {
  // Invalid native inputs are refused before the typed Rust API can be called.
  if (f.error === 'invalid i32') return '';
  const expected = f.error ? 'None' : `Some(${f.result})`;
  return `    #[test]\n    fn fixture_${i}() { assert_eq!(add(${f.args.join(', ')}), ${expected}); }\n`;
}).join('');
const adapterTests = `/// Checked addition; overflow returns None.
///
/// The typed input adapter refuses fractional and out-of-range inputs:
/// \`\`\`compile_fail
/// javascript_first_example::add(1.5, 0);
/// \`\`\`
/// \`\`\`compile_fail
/// javascript_first_example::add(2147483648, 0);
/// \`\`\`
`;
const output = `// Generated by the pinned example translator. Do not edit.\n${adapterTests}#[must_use]\npub const fn add(a: i32, b: i32) -> Option<i32> { a.checked_add(b) }\n\n#[cfg(test)]\nmod tests {\n    use super::add;\n${tests}}\n`;
const target = new URL('src/lib.rs', base);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw Error('Generated Rust drift');
} else writeFileSync(fileURLToPath(target), output);
